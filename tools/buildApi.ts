/**
 * Section 35.4: bundles the server (server/index.ts, and with it the game's core: the hazard model, the run, the
 * points, the name filter, the map data) into api/_lib/server.mjs, the one module the Vercel functions import.
 *
 * Why a bundle: src/core imports through the project's path aliases (@core, @data, @levels), which Vercel's own
 * TypeScript step for api/ does not resolve. esbuild reads them from tsconfig.json. The file is checked in, so a
 * deploy needs no extra build step; `npm run build` makes it again, and tests/apiBundle.test.ts fails when it is
 * stale. Files under api/ whose names start with "_" are not functions.
 *
 *   npm run build:api
 */
import { build, type BuildOptions } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";
import fs from "node:fs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const BUNDLE = path.join(ROOT, "api/_lib/server.mjs");

export const OPTIONS: BuildOptions = {
  absWorkingDir: ROOT,
  entryPoints: ["server/index.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  tsconfig: "tsconfig.json",
  // Installed by Vercel from package.json; Node's own modules stay imports.
  external: ["@neondatabase/serverless"],
  legalComments: "none",
  charset: "utf8",
  banner: { js: "// Generated by tools/buildApi.ts (npm run build:api) from server/ and src/. Do not edit." },
  logLevel: "warning"
};

/** The bundle's text, as it would be written now. */
export async function bundleText(): Promise<string> {
  const result = await build({ ...OPTIONS, write: false, outfile: BUNDLE });
  return result.outputFiles![0].text;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await bundleText();
  fs.mkdirSync(path.dirname(BUNDLE), { recursive: true });
  fs.writeFileSync(BUNDLE, text);
  console.log(`api/_lib/server.mjs: ${(text.length / 1024).toFixed(0)} KB`);
}
