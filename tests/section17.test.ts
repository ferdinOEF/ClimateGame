import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { passYear } from "./helpers/passYear";
import { NATURE_BASED, RETIRED_ELEMENTS } from "../src/core/elements";
import { GameState } from "../src/core/gameState";
import { answers } from "../src/core/phaseObjectives";
import { noteIdsFor, TUTORIAL_LINES } from "../src/core/mayaLines";
import { discoveryFacts } from "../src/core/facts";
import { DEFENCE_ORDER, CARD_NAME } from "../src/ui/panjim/defenceCards";
import { panjimHelpHtml } from "../src/ui/panjim/panjimHelp";
import { BOT_LEVEL, newRun } from "../tools/panjimBots/bots";
import { LEVEL_BY_ID } from "../src/levels/levels";
import { sessionRun } from "./helpers/sessionRun";

/** Section 17 (owner decisions): build cards without home counts, nature-based objectives, sand mining retired. */
describe("17.1 the build cards", () => {
  it("list the defences in a fixed order, nature-based first", () => {
    expect([...DEFENCE_ORDER]).toEqual(["dune", "sandy_vegetation", "mangrove", "khazan", "seawall", "breakwater", "small_dam"]);
  });

  it("show no home count and no Best here", () => {
    const popover = readFileSync("src/ui/buildPopover.ts", "utf8");
    const controller = readFileSync("src/app/panjimController.ts", "utf8");
    for (const gone of ["build-card-pill", "build-card-best", "Best here"]) expect(popover, gone).not.toContain(gone);
    expect(controller).not.toMatch(/cardPill|sortCards|protects: saved/);
    // The model's number still works underneath: the float after a build and the bots use it.
    expect(controller).toContain("this.run.homesSavedBy(next, coord, elementId)");
  });

  it("are not described as numbers to pick the biggest of, in Help or by Maya", () => {
    const help = panjimHelpHtml({ startYear: 2026, endYear: 2050, storms: newRun("s17-help", BOT_LEVEL).schedule });
    expect(help).not.toMatch(/numbers? on the cards|biggest|Protects \d/i);
    expect(TUTORIAL_LINES.cards).not.toMatch(/number|biggest|how many homes/i);
  });
});

describe("17.2 objectives suggest nature-based defences only", () => {
  it("the candidates are dune, pandanus, mangrove and khazan, never an engineered defence", () => {
    expect([...NATURE_BASED]).toEqual(["dune", "sandy_vegetation", "mangrove", "khazan"]);
    for (const kind of ["cyclone", "flood", "compound"] as const) {
      const ids = answers(kind);
      expect(ids.length, kind).toBeGreaterThan(0);
      for (const id of ids) expect(NATURE_BASED as readonly string[], `${kind}: ${id}`).toContain(id);
    }
  });

  it("every row of every phase, generated by the model, asks for one of the four (Panjim and the Tutorial)", () => {
    for (const level of [BOT_LEVEL, LEVEL_BY_ID.get("l00-tutorial")!]) {
      const r = sessionRun(level);
      for (const storm of r.schedule) {
        while (!r.finished && r.turnNumber < r.phaseStart(storm)) passYear(r);
        const rows = r.prep.filter((job) => job.challengeId === storm.id);
        expect(rows.length, `${level.id} ${storm.id}`).toBeGreaterThan(0);
        for (const row of rows) expect(NATURE_BASED as readonly string[], `${level.id} ${storm.id}: ${row.label}`).toContain(row.elementId);
        for (const pick of r.objective?.picks ?? []) expect(NATURE_BASED as readonly string[], pick.key).toContain(pick.elementId);
        while (!r.finished && !r.landed.has(storm.id)) passYear(r);
      }
    }
  });

  it("engineered defences stay buildable", () => {
    const beach = new GameState([{ coord: { q: 0, r: 0 }, terrainId: "beach" }]);
    expect(beach.buildableAt({ q: 0, r: 0 }).map((d) => d.id)).toContain("seawall");
    const river = new GameState([{ coord: { q: 0, r: 0 }, terrainId: "river" }]);
    expect(river.buildableAt({ q: 0, r: 0 }).map((d) => d.id)).toContain("small_dam");
  });
});

describe("17.3 sand mining is retired", () => {
  it("is never offered, on any tile", () => {
    expect(RETIRED_ELEMENTS.has("sand_mining")).toBe(true);
    for (const terrainId of ["river", "beach", "estuary", "coast", "land"]) {
      const state = new GameState([{ coord: { q: 0, r: 0 }, terrainId }]);
      expect(state.buildableAt({ q: 0, r: 0 }).map((d) => d.id), terrainId).not.toContain("sand_mining");
      expect(state.canBuild({ q: 0, r: 0 }, "sand_mining"), terrainId).toBe(false);
    }
    expect(CARD_NAME.sand_mining).toBeUndefined();
    expect(DEFENCE_ORDER as readonly string[]).not.toContain("sand_mining");
  });

  it("an old save that holds one still loads, and the mine can be demolished", () => {
    const r = newRun("s17-old-save", BOT_LEVEL);
    const river = [...r.state.placed.values()].find((tile) => tile.terrainId === "river" && !tile.scenery)!;
    const key = `${river.coord.q},${river.coord.r}`;
    const snapshot = r.snapshot();
    snapshot.elements.push([key, { elementId: "sand_mining", degradeAmount: 0 } as never]);
    r.restore(snapshot);
    expect(r.state.elements.get(key)?.elementId).toBe("sand_mining");
    expect(r.canDemolish(river.coord)).toBe(true);
    // The run goes on with it on the board.
    expect(() => passYear(r)).not.toThrow();
  });

  it("its notes are not counted in the Field Guide, and Help never names it", () => {
    const ids = noteIdsFor({ opening: true, excluded: new Set() });
    for (const fact of discoveryFacts("sand_mining")) {
      const elsewhere = fact.elements.some((el) => el !== "sand_mining" && !RETIRED_ELEMENTS.has(el));
      expect(ids.has(fact.id), fact.id).toBe(elsewhere);
    }
    expect(readFileSync("src/ui/helpModal.ts", "utf8")).not.toMatch(/Sand Mining/i);
    expect(panjimHelpHtml({ startYear: 2026, endYear: 2050, storms: [] })).not.toMatch(/sand mining/i);
  });
});
